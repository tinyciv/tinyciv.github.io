"""Extract collision geometry from approved relief art; does not modify images.

Run after changing the atlases in public/assets/relief. Requires Pillow.
"""
import json
import math
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
REFERENCE_WIDTHS = (24, 32, 32, 40, 40, 48, 48, 56, 56, 64, 64, 64)
VARIED_WIDTHS = (32, 40, 48, 56, 40, 48, 56, 64, 48, 56, 64, 64)
atlases = [
    ("atlas-A.png", 4, (32,) * 16),
    ("atlas-B.png", 4, (48,) * 16),
    ("atlas-C.png", 4, (64,) * 16),
    ("hills-reference.png", 3, REFERENCE_WIDTHS),
    ("rocky-hills-reference.png", 3, REFERENCE_WIDTHS),
    ("hills-varied.png", 3, VARIED_WIDTHS),
    ("rocky-hills-varied.png", 3, VARIED_WIDTHS),
    ("mountains-varied.png", 3, VARIED_WIDTHS),
]
bounds = []
shapes = [
    "//! Generated by tools/relief/build-shape-metadata.py from approved atlas alpha.",
    "//! Matches nearest-neighbor native rasterization and the renderer alpha cutoff.",
    "pub struct Shape { pub width: usize, pub height: usize, pub rows: &'static [u64] }",
    f"pub static SHAPES: [Shape; {len(atlases) * 16}] = [",
]
for style, (filename, atlas_rows, widths) in enumerate(atlases):
    image = Image.open(ROOT / "public/assets/relief" / filename).convert("RGBA")
    atlas_alpha = image.getchannel("A")
    cells = []
    for slot, width in enumerate(widths):
        sx = round(slot % 4 * image.width / 4)
        sy = round(slot // 4 * image.height / atlas_rows)
        ex = round((slot % 4 + 1) * image.width / 4)
        ey = round((slot // 4 + 1) * image.height / atlas_rows)
        x, y, right, bottom = atlas_alpha.crop((sx, sy, ex, ey)).point(lambda a: 255 if a >= 224 else 0).getbbox()
        cell = dict(x=sx + x, y=sy + y, width=right - x, height=bottom - y)
        if style >= 3:
            cell["nativeWidth"] = width
        cells.append(cell)
        height = math.floor(width * cell["height"] / cell["width"] + .5)
        raster = image.crop((cell["x"], cell["y"], cell["x"] + cell["width"], cell["y"] + cell["height"])).resize((width, height), Image.Resampling.NEAREST)
        rows = [sum(1 << px for px in range(width) if raster.getpixel((px, py))[3] >= 192) for py in range(height)]
        opaque_rows = []
        row_spans = []
        for occupied in rows:
            runs = []
            start = None
            for px in range(width + 1):
                solid = px < width and occupied & (1 << px)
                if solid and start is None:
                    start = px
                elif not solid and start is not None:
                    runs.append([start, px])
                    start = None
            opaque_rows.append(runs)
            row_spans.append([runs[0][0], runs[-1][1]] if runs else None)
        cell["rowSpans"] = row_spans
        cell["opaqueRows"] = opaque_rows
        shapes.append(f"    Shape {{ width: {width}, height: {height}, rows: &[" + ", ".join(f"0x{mask:x}" for mask in rows) + "] },")
    # Native lookup reserves sixteen slots per style, including unused cells.
    for _ in range(16 - len(widths)):
        shapes.append("    Shape { width: 1, height: 1, rows: &[0x0] },")
    bounds.append(cells)
shapes.append("];")
(ROOT / "src/game/relief-shapes.json").write_text(json.dumps(bounds, indent=2) + "\n")
(ROOT / "rust/src/relief_shapes.rs").write_text("\n".join(shapes) + "\n")
