"""Encode the four approved house PNGs using their original Puny palette.

Each palette entry references a pixel in the original house. The runtime can
then reuse the existing faction ramp without loading another image or treating
neutral timber/foundations as team colors. No art is painted by this script.
"""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "public/assets/buildings/house-variants"
ATLAS = Image.open(ROOT / "public/assets/puny-world/overworld.png").convert("RGBA")
OUTPUT = ROOT / "src/game/house-variant-data.ts"

lines = [
    "// Generated by scripts/build-house-variant-assets.py from approved PNGs.",
    "// Palette values are original house pixel indices; '.' is transparent.",
    "export const HOUSE_VARIANT_DATA = {",
]
for tier, name, x in [(2, "flat-roof", 64), (3, "gabled-roof", 80)]:
    # Reviewed images use the atlas's red block, paired with the gold block
    # sampled by recolorPunyBuildingPixels in the game.
    original = ATLAS.crop((x + 160, 544, x + 176, 560))
    palette = {}
    for index, pixel in enumerate(original.getdata()):
        if pixel[3] and pixel not in palette:
            palette[pixel] = index
    colors = list(palette)
    assert len(colors) <= 16
    lines += [f"  {tier}: {{", f"    palette: {list(palette.values())},", "    variants: ["]
    for variant in ["a", "b"]:
        image = Image.open(ASSETS / f"{name}-{variant}.png").convert("RGBA")
        assert image.size == (16, 16)
        encoded = "".join("." if not p[3] else format(colors.index(p), "x") for p in image.getdata())
        lines += ["      ["] + [f"        '{encoded[y * 16:(y + 1) * 16]}'," for y in range(16)] + ["      ].join(''),"]
    lines += ["    ],", "  },"]
lines += ["} as const;", ""]
OUTPUT.write_text("\n".join(lines))
