// Standalone development labs embed the same compiled artifact so their HTML
// files retain their existing no-network behavior.
declare const __TINYCIV_SIMULATION_BASE64__: string;

async function readCore(): Promise<BufferSource> {
  if (typeof __TINYCIV_SIMULATION_BASE64__ === 'string')
    return Uint8Array.from(atob(__TINYCIV_SIMULATION_BASE64__), character => character.charCodeAt(0));
  if (typeof process === 'undefined' || !process.versions?.node) {
    const response = await fetch(`${import.meta.env.BASE_URL}wasm/simulation.wasm`);
    if (!response.ok) throw new Error(`Unable to load the simulation engine (${response.status}).`);
    return response.arrayBuffer();
  }
  // Keep Node builtins out of the browser bundle. Source imports, bundled
  // headless harnesses and standalone multiplayer workers use the same core.
  const builtin = 'node:fs';
  const { existsSync, readFileSync } = await import(/* @vite-ignore */ builtin) as typeof import('node:fs');
  const candidates: (string | URL)[] = [`${process.cwd()}/public/wasm/simulation.wasm`];
  if (import.meta.url.startsWith('file:')) {
    const relative = (path: string) => new URL(path, import.meta.url);
    candidates.unshift(relative('./simulation.wasm'), relative('../../public/wasm/simulation.wasm'));
  }
  const path = candidates.find(candidate => existsSync(candidate));
  if (!path) throw new Error('Rust simulation engine is missing. Run npm run build:wasm.');
  return Uint8Array.from(readFileSync(path));
}

export const rustModule = await WebAssembly.compile(await readCore());
export const rustEngine = new WebAssembly.Instance(rustModule).exports as RustExports;
export const SIMULATION_ABI_VERSION = 13;
if (rustEngine.simulation_abi_version() !== SIMULATION_ABI_VERSION) throw new Error('Unexpected Rust simulation ABI. Rebuild the game.');
