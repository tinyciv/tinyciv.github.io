"""Rebuild the checked-in training rasters from Natural Earth (stdlib only)."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
data = json.loads((ROOT / "ne_110m_land.geojson").read_text())
polygons = []
for feature in data["features"]:
    geometry = feature["geometry"]
    polygons.extend([geometry["coordinates"]] if geometry["type"] == "Polygon" else geometry["coordinates"])

# Square samples, 0.5 degrees per tile, north at the top. Each window contains
# recognizable bays, peninsulas, or islands, together with inland contexts.
regions = [
    ("Mediterranean", -12, 28), ("Scandinavia", 0, 45),
    ("Caribbean", -98, 4), ("Madagascar", 24, -42),
    ("South America", -82, -48), ("Australia", 112, -44),
    ("Indonesia", 94, -16), ("West Africa", -25, -1),
    ("Pacific Northwest", -138, 34), ("East Asia", 112, 16),
    ("Indian Ocean", 43, -8), ("Africa Interior", 2, -22),
]
samples = []
for name, west, south in regions:
    rows = [[0] * 64 for _ in range(64)]
    for y in range(64):
        lat = south + (63.5 - y) * 0.5
        for polygon in polygons:
            # Even/odd scan conversion handles polygon holes as well.
            crossings = []
            for ring in polygon:
                for a, b in zip(ring, ring[1:]):
                    if (a[1] > lat) != (b[1] > lat):
                        crossings.append(a[0] + (lat - a[1]) * (b[0] - a[0]) / (b[1] - a[1]))
            crossings.sort()
            for a, b in zip(crossings[::2], crossings[1::2]):
                for x in range(64):
                    lon = west + (x + 0.5) * 0.5
                    if a <= lon < b:
                        rows[y][x] = 1
    samples.append({"name": name, "west": west, "south": south, "rows": ["".join(map(str, row)) for row in rows]})

target = ROOT / "earth-samples.ts"
target.write_text("// Generated by build_samples.py; source and license: PROVENANCE.md.\n"
                  "export const EARTH_SAMPLES = " + json.dumps(samples, indent=2) + " as const;\n")
print(f"Wrote {len(samples)} Natural Earth samples to {target}")
